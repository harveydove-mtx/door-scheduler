#!/usr/bin/env node
// Builds the Data Connect connector from the SQL in db/queries, so there is ONE copy of every
// query: the one db/test.sh tests. Run after changing db/queries or the list below:
//
//   node dataconnect/build-connector.mjs          # write files
//   node dataconnect/build-connector.mjs --check  # CI: fail if the committed files are stale
//
// Outputs:
//   db/queries/generated/*.sql          per-table save statements (tested by db/test.sh)
//   dataconnect/connector/operations.gql the operations the app calls
//
// Why native SQL (_select / _execute...) instead of Data Connect @table types: Data Connect
// rewrites tables to match its own type definitions, which would drop our constraints,
// defaults and triggers. With no @table types it never touches the database; the schema is
// owned by db/migrations. See docs/v2-data-model.md section 7.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const QUERIES = join(ROOT, 'db', 'queries');
const check = process.argv.includes('--check');

// Only signed-in Matrix staff (a request with no sign-in has no email, so it is refused).
// Sign-up is disabled in Firebase Auth, so accounts are the ones
// an admin created; this also rejects any account outside the Matrix domain.
const MATRIX_ONLY = "auth.token.email.endsWith('@matrixhardware.co.uk')";

// Tables whose MAT code / price can be edited from the MAT code table (v_mat_code_table).
const PRICED = [
  ['products', 'cost'],
  ['door_rates', 'price'],
  ['vp_rates', 'price'],
  ['frame_rates', 'price'],
  ['lining_rates', 'price'],
  ['architrave_types', 'price'],
  ['over_panel_rates', 'price'],
];

// ---------------------------------------------------------------------------
// Generated per-table SQL. Each statement only touches its table when $1 names it, so
// one mutation can hold all seven and exactly one of them runs (Data Connect wraps each
// statement in a CTE, so a single multi-table statement is not possible).
// ---------------------------------------------------------------------------
const generated = {};
for (const [table, col] of PRICED) {
  generated[`set_mat_code__${table}`] = `-- GENERATED by dataconnect/build-connector.mjs. Do not edit.
-- Save one MAT code on ${table}, versioned (CON-02): no row returned = someone else saved first.
-- $1 table name, $2 row id, $3 expected version, $4 MAT code (blank clears), $5 user uid
UPDATE ${table}
SET mat_code = nullif(upper(btrim($4::text)), ''), updated_by = $5::text
WHERE $1::text = '${table}' AND id = $2::uuid AND version = $3::integer
RETURNING id, version, mat_code
`;
  generated[`set_price__${table}`] = `-- GENERATED by dataconnect/build-connector.mjs. Do not edit.
-- Save one ${col === 'cost' ? 'cost' : 'price'} on ${table}, versioned (CON-02): no row returned = someone else saved first.
-- $1 table name, $2 row id, $3 expected version, $4 new price as text (e.g. '12.50'), $5 user uid
UPDATE ${table}
SET ${col} = $4::numeric, updated_by = $5::text
WHERE $1::text = '${table}' AND id = $2::uuid AND version = $3::integer
RETURNING id, version, ${col} AS price
`;
}

// ---------------------------------------------------------------------------
// Operations. params are CEL expressions bound to $1, $2... in order.
// Optional variables must always be sent by the app (null if unset).
// ---------------------------------------------------------------------------
const ops = [
  { name: 'EnsureMe', type: 'mutation', field: '_executeReturningFirst', sql: 'ensure_me',
    params: ['auth.uid', 'auth.token.email'] },
  { name: 'GetSettings', type: 'query', field: '_select', sql: 'get_settings' },
  { name: 'ListCategories', type: 'query', field: '_select', sql: 'list_categories' },
  { name: 'MatCodeTable', type: 'query', field: '_select', sql: 'mat_code_table',
    vars: { kind: 'String', onlyMissing: 'Boolean!', search: 'String', includeInactive: 'Boolean!' },
    params: ['vars.kind', 'vars.onlyMissing', 'vars.search', 'vars.includeInactive'] },
  { name: 'MatCodeOwner', type: 'query', field: '_selectFirst', sql: 'mat_code_owner',
    vars: { matCode: 'String!' }, params: ['vars.matCode'] },
  { name: 'SearchProducts', type: 'query', field: '_select', sql: 'search_products',
    vars: { search: 'String!', categoryId: 'UUID', includeInactive: 'Boolean!', limit: 'Int!' },
    params: ['vars.search', 'vars.categoryId', 'vars.includeInactive', 'vars.limit'] },
  { name: 'AddProduct', type: 'mutation', field: '_executeReturningFirst', sql: 'add_product',
    vars: { categoryId: 'UUID!', matCode: 'String', supplierCode: 'String', description: 'String!',
            finish: 'String', unit: 'String', cost: 'String!' },
    params: ['vars.categoryId', 'vars.matCode', 'vars.supplierCode', 'vars.description',
             'vars.finish', 'vars.unit', 'vars.cost', 'auth.uid'] },
  { name: 'UpdateProduct', type: 'mutation', field: '_executeReturningFirst', sql: 'update_product',
    vars: { id: 'UUID!', version: 'Int!', description: 'String!', supplierCode: 'String', finish: 'String',
            unit: 'String', active: 'Boolean!' },
    params: ['vars.id', 'vars.version', 'vars.description', 'vars.supplierCode', 'vars.finish',
             'vars.unit', 'vars.active', 'auth.uid'] },
  { name: 'SetMatCode', type: 'mutation', transaction: true,
    parts: PRICED.map(([t]) => ({ alias: t, field: '_executeReturning', sql: `generated/set_mat_code__${t}` })),
    vars: { table: 'String!', id: 'UUID!', version: 'Int!', matCode: 'String' },
    params: ['vars.table', 'vars.id', 'vars.version', 'vars.matCode', 'auth.uid'] },
  { name: 'SetPrice', type: 'mutation', transaction: true,
    parts: PRICED.map(([t]) => ({ alias: t, field: '_executeReturning', sql: `generated/set_price__${t}` })),
    vars: { table: 'String!', id: 'UUID!', version: 'Int!', price: 'String!' },
    params: ['vars.table', 'vars.id', 'vars.version', 'vars.price', 'auth.uid'] },
];

// ---------------------------------------------------------------------------

function readSql(name) {
  const text = name.startsWith('generated/') ? generated[name.slice('generated/'.length)]
    : readFileSync(join(QUERIES, `${name}.sql`), 'utf8');
  if (text === undefined) throw new Error(`unknown query ${name}`);
  const sql = text
    .split('\n')
    .map(line => line.replace(/\s+--.*$/, '').replace(/^--.*$/, '').trimEnd())
    .filter(line => line.trim() !== '')
    .join('\n    ')
    .replace(/;\s*$/, '');
  if (sql.includes('"""')) throw new Error(`${name}: SQL may not contain """`);
  return sql;
}

function field(alias, fieldName, sqlName, params) {
  const p = params.map(e => `{_expr: "${e}"}`).join(', ');
  return `  ${alias ? `${alias}: ` : ''}${fieldName}(
    sql: """
    ${readSql(sqlName)}
    """,
    params: [${p}]
  )`;
}

let gql = `# GENERATED by dataconnect/build-connector.mjs from db/queries/*.sql. Do not edit.
# Every operation: signed-in Matrix staff only. updated_by / created_by always come from
# auth.uid on the server, never from the browser.
`;
for (const op of ops) {
  const vars = Object.entries(op.vars ?? {}).map(([k, t]) => `$${k}: ${t}`).join(', ');
  const header = `${op.type} ${op.name}${vars ? `(${vars})` : ''} @auth(expr: "${MATRIX_ONLY}")${op.transaction ? ' @transaction' : ''}`;
  const body = op.parts
    ? op.parts.map(pt => field(pt.alias, pt.field, pt.sql, op.params ?? [])).join('\n')
    : field(null, op.field, op.sql, op.params ?? []);
  gql += `\n${header} {\n${body}\n}\n`;
}

const outputs = { [join(ROOT, 'dataconnect', 'connector', 'operations.gql')]: gql };
for (const [name, text] of Object.entries(generated)) outputs[join(QUERIES, 'generated', `${name}.sql`)] = text;

let stale = [];
for (const [path, text] of Object.entries(outputs)) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === text) continue;
  if (check) { stale.push(path.slice(ROOT.length + 1)); continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote ${path.slice(ROOT.length + 1)}`);
}
if (stale.length) {
  console.error(`Out of date (run node dataconnect/build-connector.mjs):\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
if (check) console.log('connector is up to date');
